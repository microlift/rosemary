#!/usr/bin/env python3
"""Write crates/darwin/src/syscall/numbers.rs from XNU's syscall tables.

On x86-64 the high byte of `%rax` picks a table and the rest indexes it, so
each class gets its own module, parsed from the source XNU builds it from:

    SYSCALL_CLASS_UNIX  bsd/kern/syscalls.master
    SYSCALL_CLASS_MACH  osfmk/kern/syscall_sw.c     (mach_trap_table)
    SYSCALL_CLASS_MDEP  osfmk/i386/machdep_call.c   (machdep_call_table64)

and the class constants from osfmk/mach/i386/syscall_sw.h. BSD names follow
<sys/syscall.h>; Mach and machine-dependent calls have no C constants, so they
take the kernel routine's name.

    tools/xnu-syscalls.py [--check]

`--check` regenerates into memory and fails if the tree disagrees.
"""

import argparse
import ast
import re
import sys
from collections.abc import Iterator
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SYSCALL_DIR = ROOT / "crates" / "darwin" / "src" / "syscall"
XNU = SYSCALL_DIR / "xnu"
BSD_MASTER = SYSCALL_DIR / "syscalls.master"
MACH_TRAPS = XNU / "osfmk" / "kern" / "syscall_sw.c"
MDEP_CALLS = XNU / "osfmk" / "i386" / "machdep_call.c"
CLASSES = XNU / "osfmk" / "mach" / "i386" / "syscall_sw.h"
OUT = SYSCALL_DIR / "numbers.rs"

BANNER = """#![allow(non_upper_case_globals)]
// Generated by tools/xnu-syscalls.py from XNU's syscall tables. Do not edit.

//! XNU syscall numbers. On x86-64, `%rax` holds a class in its high byte and
//! the number within that class's table below it.
"""

# Empty slots: removed or configured-out calls.
UNIMPLEMENTED = {"nosys", "enosys", "kern_invalid"}
INDIRECT_SYSCALL = 0

Table = list[tuple[str, int]]


def active_lines(path: Path) -> Iterator[tuple[int, str]]:
    """The lines of `path` outside a disabled conditional.

    Every condition is taken as true, as XNU's tools/syscall_map.lua does:
    the files test LP64, HYPERVISOR and kernel configs that a macOS x86-64
    kernel defines, and where a config is off the `#else` is a placeholder.
    """
    taken: list[bool] = []
    for lineno, line in enumerate(path.read_text().splitlines(), 1):
        directive = line.strip()
        if directive.startswith("#if"):
            taken.append(True)
        elif directive.startswith("#elif"):
            sys.exit(f"{path}:{lineno}: #elif has no arm to assume")
        elif directive.startswith("#else"):
            taken[-1] = not taken[-1]
        elif directive.startswith("#endif"):
            taken.pop()
        elif all(taken):
            yield lineno, line


def bsd_table(master: Path) -> Table:
    entry = re.compile(r"^(\d+)\s+\w+\s+\w+\s+\{\s*([^}]*?)\s*\}")
    function = re.compile(r"(\w+)\s*\(")
    table: Table = []
    highest = -1
    for lineno, line in active_lines(master):
        found = entry.match(line)
        if not found:
            if re.match(r"^\d", line):
                sys.exit(f"{master}:{lineno}: unparsed entry: {line}")
            continue
        number = int(found.group(1))
        if number != highest + 1:
            sys.exit(f"{master}:{lineno}: {number} out of order after {highest}")
        highest = number
        name = function.search(found.group(2))
        if not name:
            sys.exit(f"{master}:{lineno}: no function name: {line}")
        if number == INDIRECT_SYSCALL:
            table.append(("SYS_syscall", number))
        elif name.group(1) not in UNIMPLEMENTED:
            table.append(("SYS_" + name.group(1).removeprefix("sys_"), number))
    return table + [("SYS_MAXSYSCALL", highest + 1)]


def positional_table(path: Path, array: str, routine: str, count: str) -> Table:
    """A C array of routine macros, numbered by position.

    Where a slot carries a `/* N */` comment, it is checked against the
    position so a miscounted conditional cannot shift every later number.
    """
    start = re.compile(rf"\b{array}\s*\[[^]]*\]\s*=\s*\{{")
    slot = re.compile(rf"^\s*(?:/\*\s*(\d+)\s*\*/)?\s*{routine}\(\s*(\w+)")
    table: Table = []
    index = None
    for lineno, line in active_lines(path):
        if index is None:
            index = 0 if start.search(line) else None
            continue
        if line.strip().startswith("}"):
            return table + [(count, index)]
        found = slot.match(line)
        if not found:
            continue
        if found.group(1) is not None and int(found.group(1)) != index:
            sys.exit(f"{path}:{lineno}: slot {index} is labeled {found.group(1)}")
        if found.group(2) not in UNIMPLEMENTED:
            table.append((found.group(2), index))
        index += 1
    sys.exit(f"{path}: no complete {array}")


def class_constants(header: Path) -> Table:
    """`#define SYSCALL_*` from the header, values evaluated as C `int`s."""
    define = re.compile(r"^#define\s+(SYSCALL_(?:CLASS_\w+|NUMBER_MASK))\s+([^/\n]+)")
    known: dict[str, int] = {}
    for _, line in active_lines(header):
        if found := define.match(line):
            known[found.group(1)] = evaluate(found.group(2).strip(), known)
    return list(known.items())


def evaluate(expression: str, known: dict[str, int]) -> int:
    def walk(node: ast.expr) -> int:
        match node:
            case ast.Constant(value=int(value)):
                return value
            case ast.Name(id=name) if name in known:
                return known[name]
            case ast.UnaryOp(op=ast.Invert(), operand=operand):
                return ~walk(operand)
            case ast.BinOp(op=ast.LShift(), left=left, right=right):
                return walk(left) << walk(right)
        sys.exit(f"{CLASSES}: cannot evaluate `{expression}`")

    return walk(ast.parse(expression, mode="eval").body) & 0xFFFF_FFFF


def check_unique(source: Path, table: Table) -> None:
    seen: dict[str, int] = {}
    for name, number in table:
        if name in seen:
            sys.exit(f"{source}: {name} names both {seen[name]} and {number}")
        seen[name] = number


def constants(table: Table, indent: str = "") -> list[str]:
    def value(name: str, number: int) -> str:
        return f"{number:#010x}" if name.endswith("_MASK") else str(number)

    return [f"{indent}pub const {n}: u32 = {value(n, v)};" for n, v in table]


def module(doc: str, name: str, table: Table) -> list[str]:
    return ["", f"/// {doc}", f"pub mod {name} {{", *constants(table, "    "), "}"]


def render() -> str:
    bsd = bsd_table(BSD_MASTER)
    mach = positional_table(MACH_TRAPS, "mach_trap_table", "MACH_TRAP", "MACH_TRAP_TABLE_COUNT")
    mdep = positional_table(
        MDEP_CALLS, "machdep_call_table64", r"MACHDEP_(?:BSD_)?CALL_ROUTINE(?:64)?", "MACHDEP_CALL_COUNT"
    )
    for source, table in ((BSD_MASTER, bsd), (MACH_TRAPS, mach), (MDEP_CALLS, mdep)):
        check_unique(source, table)

    lines = [BANNER, *constants(class_constants(CLASSES))]
    lines += module("`SYSCALL_CLASS_UNIX`, named as <sys/syscall.h> names them.", "bsd", bsd)
    lines += module("`SYSCALL_CLASS_MACH`: `mach_trap_table`. User headers and arm64 spell these negated.", "mach", mach)
    lines += module("`SYSCALL_CLASS_MDEP`: `machdep_call_table64`.", "mdep", mdep)
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the generated file is stale")
    args = parser.parse_args()

    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT.relative_to(ROOT)} is stale: run tools/xnu-syscalls.py")
        return
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
